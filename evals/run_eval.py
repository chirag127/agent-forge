"""Eval harness — runs agent over gold dataset, scores, writes report."""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import structlog

from agent_forge.agents import Orchestrator
from agent_forge.providers import LLMConfig

log = structlog.get_logger(__name__)

GOLD_PATH = Path(__file__).parent / "gold_dataset.json"
REPORT_PATH = Path(__file__).parent / "report.md"


@dataclass
class EvalCase:
    id: str
    task: str
    assertions: list[dict[str, Any]]
    tags: list[str] = field(default_factory=list)


@dataclass
class EvalResult:
    case: EvalCase
    answer: str
    passed: bool
    failed_assertions: list[str]
    latency_s: float
    error: str = ""


def load_dataset(path: Path = GOLD_PATH) -> list[EvalCase]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return [EvalCase(**item) for item in data]


def check_assertions(answer: str, assertions: list[dict[str, Any]]) -> tuple[bool, list[str]]:
    failed: list[str] = []
    for a in assertions:
        atype = a["type"]
        if atype == "contains":
            if a["value"] not in answer:
                failed.append(f"contains '{a['value']}'")
        elif atype == "contains_ci":
            if a["value"].lower() not in answer.lower():
                failed.append(f"contains_ci '{a['value']}'")
        elif atype == "contains_any":
            if not any(v in answer for v in a["values"]):
                failed.append(f"contains_any {a['values']}")
        elif atype == "contains_any_ci":
            if not any(v.lower() in answer.lower() for v in a["values"]):
                failed.append(f"contains_any_ci {a['values']}")
        elif atype == "not_contains":
            if a["value"] in answer:
                failed.append(f"not_contains '{a['value']}'")
        elif atype == "llm_judge":
            # placeholder — treat as pass if answer non-empty
            if not answer.strip():
                failed.append("llm_judge: empty answer")
    return len(failed) == 0, failed


def run_evals(
    dataset_path: Path = GOLD_PATH,
    report_path: Path = REPORT_PATH,
    llm_config: LLMConfig | None = None,
) -> list[EvalResult]:
    cases = load_dataset(dataset_path)
    orchestrator = Orchestrator(llm_config=llm_config)
    results: list[EvalResult] = []

    for case in cases:
        log.info("eval.running", id=case.id, task=case.task[:60])
        t0 = time.monotonic()
        error = ""
        answer = ""
        try:
            run = orchestrator.run(case.task)
            answer = run.final_answer
        except Exception as e:  # noqa: BLE001
            error = str(e)
            log.warning("eval.error", id=case.id, error=error)

        latency = time.monotonic() - t0
        passed, failed = check_assertions(answer, case.assertions)
        results.append(EvalResult(
            case=case,
            answer=answer,
            passed=passed,
            failed_assertions=failed,
            latency_s=round(latency, 2),
            error=error,
        ))
        status = "PASS" if passed else "FAIL"
        log.info("eval.done", id=case.id, status=status, latency_s=round(latency, 2))

    _write_report(results, report_path)
    return results


def _write_report(results: list[EvalResult], path: Path) -> None:
    total = len(results)
    passed = sum(1 for r in results if r.passed)
    pct = round(passed / total * 100, 1) if total else 0

    lines = [
        "# Agent Forge — Eval Report",
        "",
        f"**Total:** {total} | **Passed:** {passed} | **Failed:** {total - passed} | **Pass rate:** {pct}%",
        "",
        "| ID | Task (truncated) | Pass | Latency (s) | Failed assertions |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        status = "✓" if r.passed else "✗"
        task_short = r.case.task[:50].replace("|", "\\|")
        failed_str = "; ".join(r.failed_assertions) or ""
        if r.error:
            failed_str = f"ERROR: {r.error[:60]}"
        lines.append(f"| {r.case.id} | {task_short} | {status} | {r.latency_s} | {failed_str} |")

    lines += ["", "---", f"*Generated by agent-forge eval harness — {total} cases*"]
    path.write_text("\n".join(lines), encoding="utf-8")
    log.info("eval.report_written", path=str(path))


if __name__ == "__main__":
    from agent_forge.observability import configure
    configure()
    results = run_evals()
    passed = sum(1 for r in results if r.passed)
    print(f"\nResults: {passed}/{len(results)} passed")
